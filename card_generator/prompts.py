def build_user_prompt(product_json: str, missing: list[str], feedback: list[str] | None = None) -> str:
    text = (
        "<product>\n" + product_json + "\n</product>\n\n"
        "Заранее найденные пробелы во входных данных: "
        + (", ".join(missing) if missing else "нет")
        + ".\nСформируй карточку."
    )
    if feedback:
        text += (
            "\n\nПредыдущая попытка не прошла проверку. Исправь и верни JSON заново:\n- "
            + "\n- ".join(feedback)
        )
    return text
